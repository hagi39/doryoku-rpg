  /** "1,math_21" のような参照を完全な skill id に開く */
  function expandRefs(treeId, csv) {
    if (!csv) return [];
    return String(csv).split(',').map(function (raw) {
      const s = raw.trim();
      if (!s) return null;
      return /^\d+$/.test(s) ? makeId(treeId, Number(s)) : normalizeCrossRef(s);
    }).filter(Boolean);
  }

  function makeId(treeId, n) {
    return treeId + '_' + String(n).padStart(2, '0');
  }

  /** "math_21" → "math_21"、"low_5" → "low_05" */
  function normalizeCrossRef(s) {
    const m = /^([a-z]+)_(\d+)$/.exec(s);
    return m ? makeId(m[1], Number(m[2])) : s;
  }

  function parseReward(str) {
    const out = {};
    if (!str) return out;
    for (const part of String(str).split(',')) {
      const [k, v] = part.split(':');
      if (k && v) out[k.trim()] = Number(v);
    }
    return out;
  }

